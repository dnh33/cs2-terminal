export function getDropTable(caseId: string): CaseDropTable | undefined {
  return DROP_TABLE[caseId]
}

export function uniqueHighTierItems(): string[] {
  const set = new Set<string>()
  for (const c of Object.values(DROP_TABLE)) c.high_tier_items.forEach(n => set.add(n))
  return [...set].sort()
}

export function uniqueLowTierItems(): string[] {
  const set = new Set<string>()
  for (const c of Object.values(DROP_TABLE)) c.low_tier_items.forEach(n => set.add(n))
  return [...set].sort()
}

export function itemToCases(): Map<string, string[]> {
  const m = new Map<string, string[]>()
  for (const [caseId, c] of Object.entries(DROP_TABLE)) {
    for (const item of [...c.high_tier_items, ...c.low_tier_items]) {
      const arr = m.get(item) ?? []
      arr.push(caseId)
      m.set(item, arr)
    }
  }
  return m
}
